// Builds migrations/2026-10-31-release.sql: every SQL file of the release, in
// order, inside ONE transaction that ends with schema-lockdown.sql.
//
// WHY ONE TRANSACTION. Applied file by file, every function a file creates is
// callable by anon and authenticated (Supabase's default grants) until
// schema-lockdown.sql runs last: test/migration-review.test.mjs measured 18
// such functions and 3 backup tables in that window. Postgres DDL is
// transactional, so inside one transaction no other session, and so no
// PostgREST request, ever sees the unlocked state. A failure anywhere rolls
// the whole release back.
//
// Run: node scripts/build-release-sql.mjs   (rewrite the file after any
// schema change; test/migration-review.test.mjs checks it is current).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RELEASE_ORDER = ['migrations/2026-10-31-device-attribution.sql', 'schema-billing.sql',
  'schema-community.sql', 'schema-misses.sql', 'schema-deletion.sql', 'schema-retention.sql',
  'schema-contributor-migration.sql', 'schema-dish-cleanup.sql', 'schema-lockdown.sql'];

export function buildRelease() {
  const parts = RELEASE_ORDER.map(file => {
    const body = readFileSync(path.join(ROOT, file), 'utf8')
      .split('\n')
      .filter(line => !/^\s*(begin|commit)\s*;\s*(--.*)?$/i.test(line))
      .join('\n');
    return `-- ===== ${file} =====\n${body}\n`;
  });
  return `-- GENERATED by scripts/build-release-sql.mjs. Do not edit by hand.
-- The 2026-10-31 release, applied atomically: ${RELEASE_ORDER.length} files, lockdown last.
-- Run in the Agni Supabase project (nglfxnzxseshrklypxhg; check the name first)
-- BEFORE the server deploy. Safe to run again: a second run changes nothing.
begin;
${parts.join('\n')}
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(ROOT, 'migrations/2026-10-31-release.sql'), buildRelease());
  console.log('wrote migrations/2026-10-31-release.sql');
}
